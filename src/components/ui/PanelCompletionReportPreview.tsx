import CompanyLogo from './CompanyLogo';

export interface PanelCompletionReportPreviewData {
  project: {
    code: string;
    name: string;
    client: string | null;
    locationRegion: string | null;
    monthYear: string | null;
  };
  panel: {
    id: string;
    name: string;
    panelType: string | null;
    voltageLevel: string | null;
  };
  reportStatus: string;
  reportStatusLabel: string;
  /** 'progress' while the panel is in execution; 'completion' only once wired + approved. */
  reportKind: 'progress' | 'completion';
  reportTitle: string;
  approval: {
    approved: boolean;
    approvedAt: string | null;
    approvedBy: { fullName: string } | null;
  };
  technicians: { fullName: string; username: string }[];
  technician: { fullName: string; username: string } | null;
  midChangeTechnician: { fullName: string; username: string } | null;
  contributions: {
    assignmentId: number;
    technician: { fullName: string; username: string };
    startedAt: string | null;
    endedAt: string | null;
    durationSeconds: number;
    durationHuman: string;
    cablesCompleted: number;
    sourceEndsCompleted: number;
    destinationEndsCompleted: number;
    progressBefore: number;
    progressAfter: number;
    sessionLog: { loginAt: string; logoutAt: string | null }[];
  }[];
  midChangeHistory: {
    action: string;
    technicianName: string;
    at: string | null;
    details: string;
  }[];
  supervisor: { fullName: string } | null;
  assignedBy: { fullName: string } | null;
  cables: {
    total: number;
    completed: number;
    remaining: number;
    openEndSource: number;
    openEndDestination: number;
  };
  wiring: {
    startedAt: string | null;
    completedAt: string | null;
    durationHuman: string;
  };
  sessionLog: { loginAt: string; logoutAt: string | null }[];
  totalWorkingHours: string;
  completionPercent: number;
  kpi: number;
  projectDurationDays: number;
  rework: { count: number; status: string; reason: string };
  technicianRemarks: string[];
  supervisorRemarks: string;
  generatedBy: string;
  generatedAt: string;
}

function fmt(dt: string | null) {
  if (!dt) return '—';
  return new Date(dt).toLocaleString(undefined, {
    year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit',
  });
}

function parseSubstation(name: string, client: string | null) {
  const parts = name.split(/\s+[–—]\s+|\s+-\s+/).map(p => p.trim()).filter(Boolean);
  if (parts.length <= 1) return name.trim() || '—';
  let i = 1;
  const norm = (v: string) => v.trim().toUpperCase().replace(/\s+/g, ' ');
  if (parts[i] && client && norm(parts[i]) === norm(client)) i += 1;
  return parts[0];
}

function statusTone(status: string): string {
  switch (status) {
    case 'completed': return 'pcr-status--completed';
    default: return 'pcr-status--progress';
  }
}

