  const client = (data.project.client || '').trim() || '—';
  const substation = parseSubstation(data.project.name, data.project.client);
  const isCompletion = data.reportKind === 'completion';
  // Reference is built from what the reader can see — the internal frame id is never shown.
  const docRef = `DWES-${isCompletion ? 'PCR' : 'PPR'}-${`${data.project.code}-${data.panel.name}`
    .toUpperCase().replace(/[^A-Z0-9-]/g, '').slice(0, 30)}`;
  const loginTimes = data.sessionLog.length
    ? data.sessionLog.map(s => fmt(s.loginAt)).join(' · ')
    : '—';
  const logoutTimes = data.sessionLog.length
    ? data.sessionLog.map(s => (s.logoutAt ? fmt(s.logoutAt) : 'Active')).join(' · ')
    : '—';
  const reworkLabel = data.rework.count > 0 ? `${data.rework.count} recorded` : 'None';

  const personnel = [
    { label: 'Assigned technician(s)', name: data.technicians.map(t => t.fullName).join(', ') || '—' },
    { label: 'Production supervisor', name: data.supervisor?.fullName || '—' },
    { label: 'Report generated by', name: data.generatedBy },
  ];

